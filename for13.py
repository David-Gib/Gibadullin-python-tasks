# For13. Дано целое число N (> 0).
# Найти значение выражения 1.1 − 1.2 + 1.3 − ... (N слагаемых, знаки чередуются).
# Слагаемое с номером i равно (10 + i) / 10.
# Нечётные номера прибавляем, чётные вычитаем.
n = int(input())
total = 0.0
for i in range(1, n + 1):
    term = (10 + i) / 10
    if i % 2 == 1:
        total += term
    else:
        total -= term
print(total)
