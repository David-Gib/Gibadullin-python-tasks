# If3 с защитой. Дано целое число. Если оно положительное, прибавить 1;
# если отрицательное, вычесть из него 2; если нулевое, заменить на 10.
# Вывести результат. При нечисловом вводе вывести "Ошибка ввода".
# В try только чтение, ветки if стоят в else и не меняются.
try:
    number = int(input())
except ValueError:
    print("Ошибка ввода")
else:
    if number > 0:
        number += 1
    elif number < 0:
        number -= 2
    else:
        number = 10
    print(number)
