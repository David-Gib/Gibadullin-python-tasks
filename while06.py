# While6. Дано целое число N (> 0). Найти двойной факториал N:
# N!! = N·(N−2)·(N−4)·... (последний сомножитель равен 2, если N — четное,
# и 1, если N — нечетное). Вычислять произведение с помощью вещественной
# переменной и вывести его как вещественное число.
n = int(input())
product = 1.0
factor = n
while factor > 1:
    product *= factor
    factor -= 2
print(product)
