# If3. Дано целое число. Если оно является положительным, то прибавить к нему 1;
# если отрицательным, то вычесть из него 2; если нулевым, то заменить его на 10.
# Вывести полученное число.
number = int(input())
if number > 0:
    number += 1
elif number < 0:
    number -= 2
else:
    number = 10
print(number)
