# While4. Дано целое число N (> 0). Если оно является степенью числа 3,
# то вывести TRUE, если не является — вывести FALSE.
# Делим на 3, пока делится без остатка. Если в конце осталась единица —
# число было степенью тройки. (Python печатает True и False.)
n = int(input())
rest = n
while rest % 3 == 0:
    rest //= 3
print(rest == 1)
